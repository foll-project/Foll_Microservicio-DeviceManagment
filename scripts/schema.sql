CREATE TABLE device.device_events (
    device_event_id bigint GENERATED BY DEFAULT AS IDENTITY,
    device_id bigint NOT NULL,
    event_type character varying(50) NOT NULL,
    event_payload jsonb NOT NULL,
    is_resolved boolean NOT NULL DEFAULT FALSE,
    created_at timestamptz NOT NULL,
    resolved_at timestamptz,
    CONSTRAINT pk_device_events PRIMARY KEY (device_event_id)
);

CREATE TABLE device.devices (
    device_id bigint NOT NULL,
    assigned_patient_id bigint,
    firmware_version character varying(50) NOT NULL,
    status smallint NOT NULL,
    connectivity_status smallint,
    current_battery_level smallint,
    is_charging boolean,
    last_heartbeat_at timestamptz,
    monitoring_started_at timestamptz,
    last_connectivity_change_at timestamptz,
    CONSTRAINT pk_devices PRIMARY KEY (device_id)
);

CREATE TABLE device.outbox_messages (
    outbox_message_id bigint GENERATED BY DEFAULT AS IDENTITY,
    type character varying(500) NOT NULL,
    payload jsonb NOT NULL,
    occurred_on timestamptz NOT NULL,
    processed_on timestamptz,
    error character varying(2000),
    retry_count integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_outbox_messages PRIMARY KEY (outbox_message_id)
);

